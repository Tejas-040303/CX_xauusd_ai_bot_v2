        print(f"  Profit Factor:          {m['profit_factor']:>10.2f}")
        print(f"  Sharpe Ratio:           {m['sharpe_ratio']:>10.2f}")

        print(f"\n  {'TRADES':}")
        print(f"  Total Trades:           {m['num_trades']:>10}")
        print(f"  Win Rate:               {m['win_rate']:>9.1f}%")
