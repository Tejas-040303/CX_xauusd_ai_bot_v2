# ─── Strategy Base Class ─────────────────────────────────

class StrategyBase:
    """
    Base class for all strategies.
    Override generate_signal() in subclasses.
    """

    name: str = "BaseStrategy"

    def generate_signal(self, df: pd.DataFrame, idx: int) -> Optional[TradeSignal]:
        """
        Check if there's a trade signal at the given index.

        Args:
            df: Full feature-engineered DataFrame
            idx: Current candle index (only use data up to and including idx)

        Returns:
            TradeSignal if there's a valid signal, None otherwise.
            
        IMPORTANT: Only use df.iloc[:idx+1] to avoid lookahead bias!
        """
        raise NotImplementedError("Subclasses must implement generate_signal()")


# ─── Dummy Strategy for Testing ──────────────────────────

class DummyStrategy(StrategyBase):
    """
    Simple EMA crossover strategy for testing the backtester.
    NOT for production — just validates that the backtester works correctly.
    """

    name = "DummyEMACross"

    def generate_signal(self, df: pd.DataFrame, idx: int) -> Optional[TradeSignal]:
        # Need at least 200 candles for EMA200
        if idx < 200:
            return None

        row = df.iloc[idx]
        prev = df.iloc[idx - 1]

        # Only check once per 5 candles (reduce signal frequency)
        if idx % 5 != 0:
            return None

        atr = row.get(f"atr_14", 2.0)  # Default ATR if not computed

        # Simple: EMA9 crosses above EMA21 = buy, below = sell
        if "ema_9" not in df.columns or "ema_21" not in df.columns:
            return None

        ema9_now = row["ema_9"]
        ema21_now = row["ema_21"]
        ema9_prev = prev["ema_9"]
        ema21_prev = prev["ema_21"]

        signal = None

        # Bullish crossover
        if ema9_prev <= ema21_prev and ema9_now > ema21_now:
            sl = row["close"] - 2 * atr
            tp = row["close"] + 3 * atr
            signal = TradeSignal(
                datetime=row["datetime"],
                direction="buy",
                strategy_name=self.name,
                confidence=70,
                sl_price=sl,
                tp_price=tp,
                entry_price=row["close"],
                sub_conditions={"ema_cross": True, "above_ema200": bool(row.get("above_ema200", 0))},
            )

        # Bearish crossover
        elif ema9_prev >= ema21_prev and ema9_now < ema21_now:
            sl = row["close"] + 2 * atr
            tp = row["close"] - 3 * atr
            signal = TradeSignal(
                datetime=row["datetime"],
                direction="sell",
                strategy_name=self.name,
                confidence=70,
                sl_price=sl,
                tp_price=tp,
                entry_price=row["close"],
                sub_conditions={"ema_cross": True, "above_ema200": bool(row.get("above_ema200", 0))},
            )

        return signal


